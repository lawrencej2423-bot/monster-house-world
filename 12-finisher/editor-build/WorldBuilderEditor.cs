// WorldBuilderEditor.cs -- Monster House world: editor-side STATIC build.
//
// Deploy to: Assets/Editor/WorldBuilderEditor.cs in the Highrise Studio
// project (the Editor folder keeps it out of the player/runtime build).
//
// Why this exists: Highrise worlds are built into the scene in the editor.
// The runtime builder (05-builder/builder.lua) can load all 203 placements
// but Object.Instantiate in Highrise Lua only accepts Prefabs, so it can
// never clone the scene-resident templates. This script does the same job
// on the editor side, where UnityEngine.Object.Instantiate on a scene
// object is the normal, supported operation.
//
// Data: Assets/Scripts/placements.json (generated by
// ec2-setup/editor-build/make_placements_json.py from the same manifests
// and the same loader as the Lua Placements module -- identical entries).
// Templates: the DIRECT children of the scene's "BuilderTemplates" object
// (132 stocked templates; the root is INACTIVE by design, so the search
// traverses the hierarchy manually instead of using GameObject.Find,
// which only sees active objects).
//
// Run it from the menu:  Monster House > Build World (Static)
// It is menu-triggered ONLY -- no InitializeOnLoad, no ExecuteInEditMode,
// nothing runs during Play. Re-running is safe: the previous BuiltWorld
// children are deleted first (clean rebuild, idempotent). The build marks
// the scene dirty; SAVE THE SCENE afterwards to persist it.

using System;
using System.Collections.Generic;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

public static class WorldBuilderEditor
{
    private const string PlacementsPath = "Assets/Scripts/placements.json";
    private const string TemplatesRootName = "BuilderTemplates";
    private const string BuiltRootName = "BuiltWorld";
    private const string SkipName = "SpawnPoint"; // already in the world
    private const string LogTag = "[WorldBuilderEditor]";

    // ---- JsonUtility mirror classes (field names are case-sensitive and
    // ---- must match placements.json exactly) ---------------------------

    [Serializable]
    private class PlacementsFile
    {
        public PlacementEntry[] entries;
    }

    [Serializable]
    private class PlacementEntry
    {
        public string name;
        public string asset;
        public float x;
        public float y;
        public float z;
        public float ry;
        public bool hasScale;
        public float sx;
        public float sy;
        public float sz;
        public bool active;
    }

    // ---- Menu entry point ------------------------------------------------

    [MenuItem("Monster House/Build World (Static)")]
    public static void BuildWorldStatic()
    {
        // 1. Load + parse the placements data.
        TextAsset textAsset = AssetDatabase.LoadAssetAtPath<TextAsset>(PlacementsPath);
        if (textAsset == null)
        {
            Debug.LogError(LogTag + " Could not load " + PlacementsPath +
                           " -- build aborted.");
            return;
        }

        PlacementsFile data = JsonUtility.FromJson<PlacementsFile>(textAsset.text);
        if (data == null || data.entries == null)
        {
            Debug.LogError(LogTag + " " + PlacementsPath +
                           " parsed to no entries -- build aborted.");
            return;
        }

        Scene scene = SceneManager.GetActiveScene();
        if (!scene.IsValid() || !scene.isLoaded)
        {
            Debug.LogError(LogTag + " No loaded active scene -- build aborted.");
            return;
        }

        // 2. Find BuilderTemplates (may be inactive -- traverse manually)
        //    and map its DIRECT children by name.
        GameObject templatesRoot = FindInSceneDeep(scene, TemplatesRootName);
        if (templatesRoot == null)
        {
            Debug.LogError(LogTag + " '" + TemplatesRootName +
                           "' not found in scene '" + scene.name +
                           "' -- build aborted.");
            return;
        }

        var templates = new Dictionary<string, GameObject>();
        Transform templatesTransform = templatesRoot.transform;
        for (int i = 0; i < templatesTransform.childCount; i++)
        {
            GameObject child = templatesTransform.GetChild(i).gameObject;
            if (templates.ContainsKey(child.name))
            {
                Debug.LogWarning(LogTag + " Duplicate template name '" +
                                 child.name + "' -- keeping the first.");
                continue;
            }
            templates.Add(child.name, child);
        }

        if (templates.Count == 0)
        {
            Debug.LogError(LogTag + " '" + TemplatesRootName +
                           "' has no children -- nothing stocked, build aborted.");
            return;
        }

        // 3. Find or create the BuiltWorld root; clear any previous build.
        GameObject builtWorld = FindSceneRoot(scene, BuiltRootName);
        if (builtWorld == null)
        {
            builtWorld = new GameObject(BuiltRootName);
            Undo.RegisterCreatedObjectUndo(builtWorld, "Build World (Static)");
        }
        else
        {
            Transform bt = builtWorld.transform;
            for (int i = bt.childCount - 1; i >= 0; i--)
            {
                Undo.DestroyObjectImmediate(bt.GetChild(i).gameObject);
            }
        }

        // 4. Clone one object per entry.
        int placed = 0;
        int skipped = 0;
        int missing = 0;

        foreach (PlacementEntry entry in data.entries)
        {
            if (entry == null || string.IsNullOrEmpty(entry.name))
            {
                skipped++;
                continue;
            }

            if (entry.name == SkipName)
            {
                skipped++;
                continue;
            }

            GameObject template;
            if (entry.asset == null ||
                !templates.TryGetValue(entry.asset, out template) ||
                template == null)
            {
                missing++;
                Debug.LogWarning(LogTag + " Missing template '" + entry.asset +
                                 "' for placement '" + entry.name +
                                 "' -- skipped.");
                continue;
            }

            GameObject clone = UnityEngine.Object.Instantiate(template);
            Undo.RegisterCreatedObjectUndo(clone, "Build World (Static)");

            clone.name = entry.name;
            clone.transform.SetParent(builtWorld.transform, false);
            clone.transform.position = new Vector3(entry.x, entry.y, entry.z);
            clone.transform.rotation = Quaternion.Euler(0f, entry.ry, 0f);
            clone.transform.localScale = entry.hasScale
                ? new Vector3(entry.sx, entry.sy, entry.sz)
                : template.transform.localScale;
            clone.SetActive(entry.active);

            placed++;
        }

        // 5. Summary + persist reminder.
        Debug.Log(string.Format("{0} placed={1} skipped={2} missing={3}",
                                LogTag, placed, skipped, missing));

        EditorSceneManager.MarkSceneDirty(scene);
        Debug.Log(LogTag + " Scene marked dirty -- save the scene " +
                  "(Ctrl+S) to persist the build.");
    }

    // ---- Scene search helpers (inactive-safe) ----------------------------

    /// <summary>Find a GameObject anywhere in the scene, including
    /// inactive ones, by recursive traversal from the roots.</summary>
    private static GameObject FindInSceneDeep(Scene scene, string name)
    {
        List<GameObject> roots = new List<GameObject>(scene.GetRootGameObjects());
        for (int i = 0; i < roots.Count; i++)
        {
            GameObject found = FindDeep(roots[i], name);
            if (found != null)
            {
                return found;
            }
        }
        return null;
    }

    private static GameObject FindDeep(GameObject go, string name)
    {
        if (go.name == name)
        {
            return go;
        }
        Transform t = go.transform;
        for (int i = 0; i < t.childCount; i++)
        {
            GameObject found = FindDeep(t.GetChild(i).gameObject, name);
            if (found != null)
            {
                return found;
            }
        }
        return null;
    }

    /// <summary>Find a GameObject that sits directly at the scene root.</summary>
    private static GameObject FindSceneRoot(Scene scene, string name)
    {
        List<GameObject> roots = new List<GameObject>(scene.GetRootGameObjects());
        for (int i = 0; i < roots.Count; i++)
        {
            if (roots[i].name == name)
            {
                return roots[i];
            }
        }
        return null;
    }
}
